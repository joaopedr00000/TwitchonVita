#include "twitch.h"
#include "i18n.h"
#include <assert.h>
#include <string.h>
int main(void){
    if(!twitch_video_subscriber_type("SUB_ONLY_LIVE")||twitch_video_subscriber_type("UNKNOWN")||twitch_video_subscriber_type("ALL_ACCESS_PASS")||twitch_video_subscriber_type(NULL))return 1;
    twitch_media_t media[3]={0};
    strcpy(media[0].id,"100");strcpy(media[1].id,"200");strcpy(media[2].id,"300");
    int seen=0;
    assert(twitch_parse_media_restrictions("{\"data\":{\"v0\":{\"id\":\"100\",\"resourceRestriction\":{\"type\":\"SUB_ONLY_LIVE\"}},\"v1\":{\"id\":\"200\",\"resourceRestriction\":null},\"v2\":{\"id\":\"300\",\"resourceRestriction\":{\"type\":\"ALL_ACCESS_PASS\"}}}}",media,3,&seen)==1);
    assert(seen==3&&media[0].subscriber_only&&!media[1].subscriber_only&&!media[2].subscriber_only);
    assert(twitch_parse_media_restrictions("{\"data\":{\"v1\":{\"id\":\"200\",\"restriction\":{\"type\":\"subscriber_only\",\"reason\":\"\"}},\"v2\":{\"id\":\"wrong\",\"restriction\":{\"type\":\"SUB_ONLY\"}}},\"errors\":[{}]}",media,3,&seen)==1);
    assert(seen==1&&media[0].subscriber_only&&media[1].subscriber_only&&!media[2].subscriber_only);
    assert(twitch_parse_media_restrictions("{\"errors\":[{\"message\":\"Forbidden\"}]}",media,3,&seen)<0);
    assert(!media[2].subscriber_only&&seen==0);
    char more[VT_MEDIA_CURSOR];
    assert(twitch_parse_media_cursor("{\"data\":[],\"pagination\":{\"cursor\":\"abc+/=\"}}",VT_MEDIA_HELIX,0,more,sizeof(more))==0&&!strcmp(more,"abc+/="));
    assert(twitch_parse_media_cursor("{\"data\":[],\"pagination\":{}}",VT_MEDIA_HELIX,4,more,sizeof(more))==0&&!more[0]);
    assert(twitch_parse_media_cursor("{\"data\":{\"user\":{\"clips\":{\"edges\":[{\"cursor\":\"first\"},{\"cursor\":\"last\"}],\"pageInfo\":{\"hasNextPage\":true}}}}}",VT_MEDIA_GQL,4,more,sizeof(more))==0&&!strcmp(more,"last"));
    assert(twitch_parse_media_cursor("{\"data\":{\"user\":{\"videos\":{\"edges\":[],\"pageInfo\":{\"hasNextPage\":true}}}}}",VT_MEDIA_GQL,0,more,sizeof(more))<0&&!more[0]);
    assert(twitch_parse_media_cursor("{\"data\":[],\"pagination\":{\"cursor\":\"too-long\"}}",VT_MEDIA_HELIX,0,more,3)<0&&!more[0]);
    char url[96],bio[32];
    assert(twitch_channel_url("gaules",url,sizeof(url))==0);
    assert(!strcmp(url,"https://www.twitch.tv/gaules"));
    assert(twitch_channel_url("bad/path",url,sizeof(url))<0);
    assert(twitch_channel_url("abc",url,3)<0);
    assert(twitch_parse_channel_bio("{\"data\":{\"user\":{\"description\":\"Hello\"}}}",bio,sizeof(bio))==0);
    assert(!strcmp(bio,"Hello"));
    assert(twitch_parse_channel_bio("{\"data\":{\"user\":null}}",bio,sizeof(bio))<0);
    char id[32];
    assert(twitch_parse_follow_state("{\"data\":{\"user\":{\"id\":\"123\",\"self\":{\"canFollow\":true,\"follower\":null}}}}",id,sizeof(id))==0);
    assert(!strcmp(id,"123"));
    assert(twitch_parse_follow_state("{\"data\":{\"user\":{\"id\":\"123\",\"self\":{\"canFollow\":false,\"follower\":{}}}}}",id,sizeof(id))==1);
    assert(twitch_parse_follow_state("{\"data\":{\"user\":{\"id\":\"123\",\"self\":{\"canFollow\":false,\"follower\":null}}}}",id,sizeof(id))==2);
    assert(twitch_parse_follow_state("{\"errors\":[{}],\"data\":{\"user\":{\"id\":\"123\",\"self\":{\"canFollow\":true,\"follower\":null}}}}",id,sizeof(id))<0);
    assert(twitch_parse_follow_state("{\"data\":{\"user\":{\"id\":\"123\",\"self\":{}}}}",id,sizeof(id))<0);
    assert(twitch_parse_helix_follow("{\"data\":[]}","123")==0);
    assert(twitch_parse_helix_follow("{\"data\":[{\"broadcaster_id\":\"123\"}]}","123")==1);
    assert(twitch_parse_helix_follow("{\"data\":[{\"broadcaster_id\":\"456\"}]}","123")==-1);
    assert(twitch_parse_helix_follow("{\"error\":\"Unauthorized\"}","123")==-1);
    twitch_category_t g[2];twitch_stream_t s[2];
    assert(twitch_parse_categories("{\"data\":[{\"id\":\"123\",\"name\":\"Game\",\"box_art_url\":\"https://static-cdn.jtvnw.net/ttv-boxart/123-{width}x{height}.jpg\"}]}",g,2)==1);
    assert(!strcmp(g[0].art,"https://static-cdn.jtvnw.net/ttv-boxart/123-144x192.jpg"));
    assert(twitch_parse_categories("{\"data\":[{\"id\":\"bad\",\"name\":\"Invalid\"}]}",g,2)==0);
    assert(twitch_parse_category_streams("{\"data\":[{\"user_login\":\"test\",\"user_name\":\"Test\",\"game_name\":\"Game\",\"viewer_count\":17,\"thumbnail_url\":\"https://example.com/{width}x{height}.jpg\"}]}",s,2)==1);
    assert(s[0].live&&s[0].viewers==17&&!strcmp(s[0].preview,"https://example.com/320x180.jpg"));
    int count=0,more=0;char cursor[64],err[128];
    assert(twitch_parse_follows_all("{\"data\":{\"currentUser\":{\"follows\":{\"edges\":[{\"cursor\":\"a\",\"node\":{\"login\":\"offline\",\"displayName\":\"Offline\",\"stream\":null}}],\"pageInfo\":{\"hasNextPage\":false}}}}}",s,2,&count,cursor,sizeof(cursor),&more,err,sizeof(err))==0);
    assert(count==1&&!s[0].live&&!strcmp(s[0].login,"offline"));
    assert(twitch_parse_gql_categories("{\"data\":{\"games\":{\"edges\":[{\"node\":{\"id\":\"123\",\"name\":\"Just Chatting\",\"slug\":\"just-chatting\",\"displayName\":\"Just Chatting\",\"boxArtURL\":\"https://example.com/cover.jpg\"}}]}}}",g,2)==1);
    assert(!strcmp(g[0].slug,"just-chatting")&&!strcmp(g[0].art,"https://example.com/cover.jpg"));
    twitch_category_cover("Just Chatting",g[0].art,sizeof(g[0].art));
    assert(!strcmp(g[0].art,"https://static-cdn.jtvnw.net/ttv-boxart/Just%20Chatting-144x192.jpg"));
    assert(!strcmp(twitch_follow_label(1,0),"Following on Twitch"));
    assert(!strcmp(twitch_follow_label(1,1),"Following on Twitch"));
    assert(!strcmp(twitch_follow_label(0,1),"Saved on Vita"));
    assert(!strcmp(twitch_follow_label(-1,0),"Follow"));
    assert(strstr(twitch_follow_notice_detail(TW_FOLLOW_LOCAL_SAVED),"saved on Vita"));
    int offset=-1;
    assert(twitch_parse_clip_source("{\"data\":{\"clip\":{\"video\":{\"id\":\"123\"},\"videoOffsetSeconds\":0}}}",id,sizeof(id),&offset)==0);
    assert(!strcmp(id,"123")&&offset==0);
    assert(twitch_parse_clip_source("{\"data\":{\"clip\":{\"video\":null,\"videoOffsetSeconds\":null}}}",id,sizeof(id),&offset)<0);
    char vodurl[512];
    assert(twitch_build_vod_url("123","%7Btoken%7D","abcd",42,vodurl,sizeof(vodurl))==0);
    assert(strstr(vodurl,"/vod/v2/123.m3u8?")&&strstr(vodurl,"&nauth=%7Btoken%7D")&&strstr(vodurl,"&nauthsig=abcd"));
    assert(!strstr(vodurl,"&token=")&&!strstr(vodurl,"&sig="));
    assert(twitch_build_vod_url("bad/path","t","s",42,vodurl,sizeof(vodurl))<0);
    assert(twitch_build_vod_url("123","t","s",42,vodurl,5)<0);
    assert(!strcmp(twitch_vod_rejection("[{\"type\":\"error\",\"error\":\"Invalid signature\"}]"),"SIGNATURE"));
    assert(!strcmp(twitch_vod_rejection("{\"message\":\"Subscribers only\"}"),"SUBSCRIPTION"));
    assert(!strcmp(twitch_vod_rejection("[{\"error_code\":\"vod_manifest_restricted\"}]"),"DENIED"));
    assert(!strcmp(twitch_vod_rejection("{\"error_code\":\"unauthorized_entitlements\"}"),"DENIED"));
    assert(!strcmp(twitch_vod_rejection("not JSON"),"UNKNOWN"));
    assert(!strcmp(twitch_vod_rejection("{\"error\":\"Forbidden\",\"message\":\"Subscribers only\"}"),"SUBSCRIPTION"));
    assert(vt_lang_set_code("pt-BR")==0);
    assert(!strcmp(twitch_vod_access_message("SUBSCRIPTION"),"Este vídeo está disponível apenas para inscritos no canal."));
    assert(strstr(twitch_vod_access_message("DENIED"),"Talvez"));
    assert(strstr(twitch_vod_access_message("UNKNOWN"),"inscritos"));
    assert(!strstr(twitch_vod_access_message("SIGNATURE"),"inscritos"));
    assert(!strstr(twitch_vod_access_message("SIGNATURE"),"403"));
    assert(vt_lang_set_code("es")==0);
    assert(strstr(twitch_vod_access_message("SUBSCRIPTION"),"suscriptores"));
    assert(vt_lang_set_code("en")==0);
    assert(strstr(twitch_vod_access_message("SUBSCRIPTION"),"subscribers"));
    for(int i=0;i<VT_LANG_COUNT;i++){
        assert(vt_lang_set(i)==0);
        assert(*twitch_vod_access_message("SUBSCRIPTION"));
        assert(*twitch_vod_access_message("UNKNOWN"));
        assert(!strstr(twitch_vod_access_message("UNKNOWN"),"403"));
    }
    return 0;
}
